#!/usr/bin/env python3
# gen-packet-ids.py — turns the vanilla data generator's packets.json report
# into the small properties file the Atlas bot reads.
#
# Why: packet IDs change between Minecraft versions. Reading them from the
# server's own report keeps the bot in step without hand-copied tables.
# Done: all phases and directions; protocol version from version.json.
# Not done: packet *layouts* are still written by hand in the bot.
#
# Usage: gen-packet-ids.py <vanilla-server.jar> <packets.json> <out.properties>
import json
import sys
import zipfile


def main() -> None:
    jar_path, packets_path, out_path = sys.argv[1:4]
    with zipfile.ZipFile(jar_path) as jar:
        version = json.loads(jar.read("version.json"))
    with open(packets_path, encoding="utf-8") as f:
        packets = json.load(f)
    lines = [
        "# Generated by gen-packet-ids.py from the vanilla server data report.",
        f"version.name={version['name']}",
        f"version.protocol={version['protocol_version']}",
    ]
    for phase in sorted(packets):
        for direction in sorted(packets[phase]):
            for name, info in sorted(packets[phase][direction].items()):
                short = name.removeprefix("minecraft:")
                lines.append(f"{phase}.{direction}.{short}={info['protocol_id']}")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
